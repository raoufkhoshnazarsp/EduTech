def create(phase):
    cmd = ["noqte-kanban", "create", "--title", phase["title"],
           "--description", phase["desc"], "--priority", phase["priority"],
           "--skip-review"]
    for s in phase["subs"]:
        cmd += ["--subtask", s]
    out = subprocess.run(cmd, capture_output=True, text=True)
    if out.returncode != 0:
        print("FAIL", phase["title"], out.stderr[:300])
        return None
    try:
        data = json.loads(out.stdout)
    except json.JSONDecodeError:
        print("BAD OUTPUT", phase["title"], out.stdout[:200])
        return None
    t = data.get("task", {})
    if data.get("duplicate"):
        print("DUP  ", t.get("sequence_number"), phase["title"])
    else:
        print("OK   ", t.get("sequence_number"), phase["title"], f"({len(phase['subs'])} زیرمرحله)")
    return t


if __name__ == "__main__":
    if "--dry" in sys.argv:
        for p in PHASES:
            print(p["priority"], len(p["subs"]), p["title"])
        sys.exit(0)
    for p in PHASES:
        create(p)
